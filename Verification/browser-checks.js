async (page) => {
await page.goto("http://127.0.0.1:5288/ApiKeyTest");
const assert = (condition, name) => { if (!condition) throw new Error(name); };
const consoleErrors = [];
const pageErrors = [];
const requests = [];
page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()); });
page.on('pageerror', error => pageErrors.push(error.message));
page.on('request', request => requests.push({ url: request.url(), method: request.method(), body: request.postData(), headers: request.headers() }));
const input = page.getByRole('textbox', { name: '輸入內容' });
const output = page.getByRole('textbox', { name: '回傳結果' });
const button = page.getByRole('button', { name: '送出測試' });
const status = page.getByRole('status');
assert(await input.inputValue() === '' && await output.inputValue() === '', 'initial empty fields');
assert(await output.getAttribute('readonly') !== null, 'readonly result');
await input.fill(' \n ');
await button.click();
assert((await status.innerText()).includes('請輸入'), 'blank validation');
assert(requests.filter(r => r.method === 'POST').length === 0, 'blank no POST');
await input.fill('😀'.repeat(2001));
await button.click();
assert((await status.innerText()).includes('4,000'), 'UTF16 overflow validation');
assert((await input.inputValue()).length === 4002, 'no silent truncation');
assert(requests.filter(r => r.method === 'POST').length === 0, 'overflow no POST');
await input.fill('a'.repeat(3999) + '\n');
await button.click();
assert((await status.innerText()).includes('4,000'), 'native POST newline overflow rejected before request');
assert(requests.filter(r => r.method === 'POST').length === 0, 'newline overflow no POST');
await input.fill('a'.repeat(3998) + '\n');
await button.click({ noWaitAfter: true });
await page.waitForFunction(() => document.getElementById('test-status').textContent.includes('測試成功'));
assert((await input.inputValue()) === 'a'.repeat(3998) + '\n', 'boundary newline input preserved');
requests.length = 0;
await input.fill('😀'.repeat(2000));
await button.click({ noWaitAfter: true });
assert(await button.isDisabled(), 'button disabled while processing');
assert((await status.innerText()).includes('處理中'), 'busy status');
await page.evaluate(() => document.getElementById('api-key-test-form').requestSubmit());
await page.waitForFunction(() => document.getElementById('test-status').textContent.includes('測試成功'));
assert(await output.inputValue() === '模擬回覆\n第二行', 'reply newlines');
assert(await button.isEnabled(), 'button restored');
assert(requests.filter(r => r.method === 'POST').length === 1, 'one POST after repeated submit');
await input.fill('simulate:script');
await button.click({ noWaitAfter: true });
assert(await output.inputValue() === '', 'old result cleared while processing');
await page.waitForFunction(() => document.getElementById('test-status').textContent.includes('測試成功'));
assert((await output.inputValue()).includes('<script>'), 'script displayed as text');
assert(await page.evaluate(() => window.secretExecuted === undefined), 'script not executed');
await input.fill('simulate:leading-newline');
await button.click({ noWaitAfter: true });
await page.waitForFunction(() => document.getElementById('test-status').textContent.includes('測試成功'));
assert(await output.inputValue() === '\n\n第一行\n第二行', 'response leading newlines preserved');
await input.fill('simulate:quota');
await button.click({ noWaitAfter: true });
await page.waitForFunction(() => document.getElementById('test-status').textContent.includes('配額限制'));
assert(await output.inputValue() === '' && await button.isEnabled(), 'failure clears result and recovers');
await input.fill('simulate:truncated');
await button.click({ noWaitAfter: true });
await page.waitForFunction(() => document.getElementById('test-status').textContent.includes('內容可能不完整'));
assert(await output.inputValue() === '模擬回覆\n第二行', 'truncated reply preserved');
await page.setViewportSize({ width: 390, height: 844 });
const upper = await input.boundingBox();
const lower = await output.boundingBox();
assert(lower.y > upper.y + upper.height, 'mobile vertical layout');
assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile no horizontal overflow');
const allRequestsLocal = requests.every(r => new URL(r.url).hostname === '127.0.0.1');
assert(allRequestsLocal, 'browser requests stay local');
assert(!requests.some(r => JSON.stringify(r).includes('synthetic-secret-never-a-real-key')), 'credentials absent from browser requests');
assert(!(await page.content()).includes('synthetic-secret-never-a-real-key'), 'credentials absent from HTML');
assert(consoleErrors.length === 0 && pageErrors.length === 0, 'no console or runtime errors');
await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
await page.screenshot({ path: '/private/tmp/gemini-api-key-test-mobile.png', fullPage: true });
await page.setViewportSize({ width: 1280, height: 900 });
await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
await page.screenshot({ path: '/private/tmp/gemini-api-key-test-desktop.png', fullPage: true });

const chatKey = 'synthetic-chat-key-never-a-real-key';
const chatRequestStart = requests.length;
await page.goto('http://127.0.0.1:5288/ApiKeyChat');
await page.getByLabel('Gemini API Key').fill(chatKey);
await page.getByRole('button', { name: '開始對話' }).click({ noWaitAfter: true });
await page.waitForFunction(() => document.getElementById('api-key-chat') !== null);
assert(await page.locator('#chat-current-model').innerText() === 'gemini-3.8-flash', 'chat starts with default model');
await page.locator('#SelectedModelId').selectOption('gemini-3.5-flash-lite');
const changeResponsePromise = page.waitForResponse(response => response.request().method() === 'POST'
    && new URL(response.url()).searchParams.get('handler') === 'ChangeModel');
await page.getByRole('button', { name: '切換模型' }).click({ noWaitAfter: true });
const changeResponse = await changeResponsePromise;
const chatRequests = requests.slice(chatRequestStart);
const changeRequest = chatRequests.find(request => request.method === 'POST'
    && new URL(request.url).searchParams.get('handler') === 'ChangeModel');
assert(changeResponse.status() === 302, `model switch should redirect, got HTTP ${changeResponse.status()}`);
assert(changeRequest !== undefined && changeRequest.body.includes('SelectedModelId=gemini-3.5-flash-lite'), 'model switch POST includes selected model');
assert(!changeRequest.body.includes(chatKey), 'model switch POST omits API key');
await page.waitForFunction(() => document.getElementById('chat-current-model')?.textContent.trim() === 'gemini-3.5-flash-lite');
assert(await page.locator('#chat-current-model').innerText() === 'gemini-3.5-flash-lite', 'chat displays changed model');
const keyRequests = chatRequests.filter(request => request.body?.includes(chatKey));
assert(keyRequests.length === 1 && new URL(keyRequests[0].url).searchParams.get('handler') === 'Begin', 'synthetic key is sent only on Begin');
assert(!chatRequests.some(request => new URL(request.url).searchParams.get('handler') === 'Send'), 'model switch sends no chat message');
assert(!(await page.content()).includes(chatKey), 'synthetic key is absent from chat HTML');
assert(!chatRequests.some(request => new URL(request.url).hostname !== '127.0.0.1'), 'chat flow stays on local fake host');

const allChatRequestsLocal = chatRequests.every(request => new URL(request.url).hostname === '127.0.0.1');
assert(allRequestsLocal && allChatRequestsLocal, 'browser requests stay local');
assert(consoleErrors.length === 0 && pageErrors.length === 0, 'no console or runtime errors');
return { passed: true, scenarios: 'API key page validation, chat model switch, model payload, key protection, no chat submission, local network, clean console', postCount: requests.filter(r => r.method === 'POST').length + chatRequests.filter(r => r.method === 'POST').length, consoleErrors: consoleErrors.length, pageErrors: pageErrors.length };

}